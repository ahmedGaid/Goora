// Turns the shared rule vectors (test/fixtures/*.json, the ones the Dart and the
// TypeScript twins already run) into a pgTAP file, so the SQL twins of the
// pricing, direct-pay, fee-balance and cut-off rules run the SAME numbers
// (013 research D3).
//
//   node supabase/tests/gen_vector_tests.mjs            writes 60_vectors.test.sql
//   node supabase/tests/gen_vector_tests.mjs --check    exits 1 if the file is stale
//
// supabase/functions/_shared/vector_sql.test.ts runs the same check under
// `node --test`, so drift between the JSON and the SQL is caught with no database.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const fixtures = join(here, "..", "..", "test", "fixtures");
export const OUTPUT = join(here, "60_vectors.test.sql");

const load = (name) => JSON.parse(readFileSync(join(fixtures, `${name}_vectors.json`), "utf8"));
const q = (s) => `'${String(s).replaceAll("'", "''")}'`;
const int = (n) => (n === null || n === undefined ? "null::integer" : String(n));
const date = (s) => (s === null || s === undefined ? "null::date" : `${q(s)}::date`);

export function generate() {
  const tests = [];
  const add = (call, expected, name) => tests.push(`select is(${call}, ${expected}, ${q(name)});`);

  for (const c of load("pricing").cases) {
    add(`public.pay_cash_amount(${c.contribution}, ${c.tripCost}, ${c.riderSeats})`, int(c.cash), `pricing cash: ${c.name}`);
  }

  const dp = load("direct_pay");
  for (const c of dp.share) {
    add(
      `public.direct_pay_share(${c.contribution}, ${q(c.method)}, ${c.tripCost}, ${c.riderSeats})`,
      int(c.expect),
      `direct pay share: ${c.name}`,
    );
  }
  for (const c of dp.fee) {
    add(
      `public.direct_pay_fee(${c.contribution}, ${c.share}, ${c.tripCost}, ${c.riderSeats}, ${c.feeFree})`,
      int(c.expect),
      `direct pay fee: ${c.name}`,
    );
  }

  const fb = load("fee_balance");
  for (const c of fb.due) {
    add(`public.fee_due_date(${q(JSON.stringify(c.days))}::jsonb, ${date(c.today)})`, date(c.expect), `fee due: ${c.name}`);
  }
  for (const c of fb.overdue) {
    add(`public.fee_is_overdue(${date(c.due)}, ${date(c.today)})`, String(c.expect), `fee overdue: ${c.name}`);
  }
  for (const c of fb.bundle) {
    add(`public.fee_use_bundle(${c.fee}, ${c.left})`, String(c.expect), `bundle: ${c.name}`);
  }

  for (const c of load("attendance").cases) {
    if (c.fn !== "cancel") continue;
    add(
      `public.is_late(${date(c.input.rideDate)}, ${q(c.input.madeAt)}::timestamp)`,
      String(c.expect.late),
      `cut-off: ${c.name}`,
    );
  }

  return [
    "-- GENERATED by supabase/tests/gen_vector_tests.mjs from test/fixtures/*.json — do not edit.",
    "-- The SQL twins run the same vectors as the Dart and TypeScript twins (013 research D3).",
    "begin;",
    "create extension if not exists pgtap with schema extensions;",
    `select plan(${tests.length});`,
    "",
    ...tests,
    "",
    "select * from finish();",
    "rollback;",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = generate();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT, "utf8");
    } catch {
      // missing counts as stale
    }
    if (current !== text) {
      console.error("60_vectors.test.sql is stale: run node supabase/tests/gen_vector_tests.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT, text);
    console.log(`wrote ${OUTPUT}`);
  }
}
